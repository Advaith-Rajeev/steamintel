-- SteamIntel schema (ER-to-relational)
-- Run on an empty database:  psql -d steamintel -f schema.sql

-- Drop in dependency order so this file can be re-run to reset the schema.
DROP TABLE IF EXISTS game_tag       CASCADE;
DROP TABLE IF EXISTS game_genre     CASCADE;
DROP TABLE IF EXISTS game_publisher CASCADE;
DROP TABLE IF EXISTS game_developer CASCADE;
DROP TABLE IF EXISTS review         CASCADE;
DROP TABLE IF EXISTS tag            CASCADE;
DROP TABLE IF EXISTS genre          CASCADE;
DROP TABLE IF EXISTS publisher      CASCADE;
DROP TABLE IF EXISTS developer      CASCADE;
DROP TABLE IF EXISTS game           CASCADE;

-- ---------------------------------------------------------------
-- Entities
-- ---------------------------------------------------------------

CREATE TABLE game (
    app_id             INTEGER PRIMARY KEY,                  -- Steam AppID
    name               TEXT NOT NULL,
    release_date       DATE,
    price_usd          NUMERIC(8,2) CHECK (price_usd >= 0),  -- exact decimal for money
    discount_pct       SMALLINT NOT NULL DEFAULT 0
                       CHECK (discount_pct BETWEEN 0 AND 100),
    steam_deck_status  TEXT NOT NULL DEFAULT 'Unknown'
                       CHECK (steam_deck_status IN
                              ('Verified', 'Playable', 'Unsupported', 'Unknown'))
);

CREATE TABLE developer (
    developer_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT NOT NULL UNIQUE
);

CREATE TABLE publisher (
    publisher_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          TEXT NOT NULL UNIQUE
);

CREATE TABLE genre (
    genre_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      TEXT NOT NULL UNIQUE
);

CREATE TABLE tag (
    tag_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name    TEXT NOT NULL UNIQUE
);

-- One-to-one with game: the FK is NOT NULL and UNIQUE, so each game has at most
-- one review summary row, and a review row cannot exist without its game.
CREATE TABLE review (
    review_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_id            INTEGER NOT NULL UNIQUE
                      REFERENCES game(app_id) ON DELETE CASCADE,
    review_score_pct  NUMERIC(5,2) CHECK (review_score_pct BETWEEN 0 AND 100),
    total_reviews     INTEGER NOT NULL DEFAULT 0 CHECK (total_reviews >= 0)
);

-- ---------------------------------------------------------------
-- Junction tables for the many-to-many relationships
-- ---------------------------------------------------------------

CREATE TABLE game_developer (
    app_id        INTEGER NOT NULL REFERENCES game(app_id)            ON DELETE CASCADE,
    developer_id  INTEGER NOT NULL REFERENCES developer(developer_id) ON DELETE CASCADE,
    PRIMARY KEY (app_id, developer_id)
);

CREATE TABLE game_publisher (
    app_id        INTEGER NOT NULL REFERENCES game(app_id)            ON DELETE CASCADE,
    publisher_id  INTEGER NOT NULL REFERENCES publisher(publisher_id) ON DELETE CASCADE,
    PRIMARY KEY (app_id, publisher_id)
);

CREATE TABLE game_genre (
    app_id    INTEGER NOT NULL REFERENCES game(app_id)    ON DELETE CASCADE,
    genre_id  INTEGER NOT NULL REFERENCES genre(genre_id) ON DELETE CASCADE,
    PRIMARY KEY (app_id, genre_id)
);

CREATE TABLE game_tag (
    app_id  INTEGER NOT NULL REFERENCES game(app_id) ON DELETE CASCADE,
    tag_id  INTEGER NOT NULL REFERENCES tag(tag_id)  ON DELETE CASCADE,
    PRIMARY KEY (app_id, tag_id)
);

-- ---------------------------------------------------------------
-- Indexes
-- The composite primary keys already index (app_id, X). These cover the
-- reverse lookups (e.g. "all games for a genre") and the columns that the
-- demo queries filter and sort on.
-- ---------------------------------------------------------------

CREATE INDEX idx_game_developer_dev  ON game_developer (developer_id);
CREATE INDEX idx_game_publisher_pub  ON game_publisher (publisher_id);
CREATE INDEX idx_game_genre_genre    ON game_genre (genre_id);
CREATE INDEX idx_game_tag_tag        ON game_tag (tag_id);

CREATE INDEX idx_game_price          ON game (price_usd);
CREATE INDEX idx_game_release_date   ON game (release_date);
CREATE INDEX idx_review_score        ON review (review_score_pct);

